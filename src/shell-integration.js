import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const SUPPORTED_SHELLS = ['fish', 'bash', 'zsh'];

const START_MARKER = '# >>> pi-presets >>>';
const END_MARKER = '# <<< pi-presets <<<';

function quotePosix(value) {
  return `'${value.replaceAll("'", `'"'"'`)}'`;
}

function quoteFish(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function renderFunction(shell, cliPath) {
  if (shell === 'fish') {
    return `# Generated by pi-presets setup.\nfunction pi\n    command node ${quoteFish(cliPath)} $argv\nend\n`;
  }
  return `# Generated by pi-presets setup.\npi() {\n    command node ${quotePosix(cliPath)} "$@"\n}\n`;
}

function updateRc(original, block) {
  const start = original.indexOf(START_MARKER);
  const end = original.indexOf(END_MARKER);
  if (start !== -1 || end !== -1) {
    if (start === -1 || end === -1 || end < start) {
      throw new Error('Incomplete managed block in shell rc file; leaving it unchanged.');
    }
    return original.slice(0, start)
      + block
      + original.slice(end + END_MARKER.length);
  }

  const withTrailingNewline = original.length > 0 && !original.endsWith('\n')
    ? `${original}\n`
    : original;
  const separation = withTrailingNewline.length > 0 ? '\n' : '';
  return `${withTrailingNewline}${separation}${block}\n`;
}

export function installShellIntegration({ shell, repoRoot, homeDir, configHome }) {
  if (!SUPPORTED_SHELLS.includes(shell)) {
    throw new Error(`Unsupported shell: ${shell}`);
  }

  const cliPath = join(repoRoot, 'src', 'cli.js');
  if (shell === 'fish') {
    const integrationPath = join(configHome, 'fish', 'conf.d', 'pi-presets.fish');
    mkdirSync(join(configHome, 'fish', 'conf.d'), { recursive: true });
    writeFileSync(integrationPath, renderFunction(shell, cliPath));
    return { files: [integrationPath] };
  }

  const functionPath = join(configHome, 'pi-presets', 'pi.sh');
  const rcPath = join(homeDir, `.${shell}rc`);
  const quotedPath = quotePosix(functionPath);
  const block = `${START_MARKER}\n[ -f ${quotedPath} ] && . ${quotedPath}\n${END_MARKER}`;
  const original = existsSync(rcPath) ? readFileSync(rcPath, 'utf8') : '';
  const updated = updateRc(original, block);

  mkdirSync(join(configHome, 'pi-presets'), { recursive: true });
  writeFileSync(functionPath, renderFunction(shell, cliPath));
  writeFileSync(rcPath, updated);
  return { files: [functionPath, rcPath] };
}
