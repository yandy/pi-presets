import { existsSync, mkdirSync, readFileSync, rmSync, rmdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const SUPPORTED_SHELLS = ['fish', 'bash', 'zsh'] as const;
export type SupportedShell = typeof SUPPORTED_SHELLS[number];

export interface ShellIntegrationOptions {
  shell: SupportedShell;
  repoRoot: string;
  homeDir: string;
  configHome: string;
}

export interface ShellIntegrationResult {
  files: string[];
}

export function isSupportedShell(value: string): value is SupportedShell {
  return (SUPPORTED_SHELLS as readonly string[]).includes(value);
}

const START_MARKER = '# >>> pi-presets >>>';
const END_MARKER = '# <<< pi-presets <<<';

function quotePosix(value: string): string {
  return `'${value.replaceAll("'", `'"'"'`)}'`;
}

function quoteFish(value: string): string {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

export function renderFunctionSource(shell: SupportedShell, repoRoot: string): string {
  const cliPath = join(repoRoot, 'src', 'cli.ts');
  if (shell === 'fish') {
    return `# Generated by pi-presets setup.\nfunction pi\n    command node ${quoteFish(cliPath)} $argv\nend\n`;
  }
  return `# Generated by pi-presets setup.\npi() {\n    command node ${quotePosix(cliPath)} "$@"\n}\n`;
}

// Fixed examples instead of names derived from the preset directories: the hint
// is meant to be pasted into a shell, and a preset added later would otherwise
// make the printed list stale (setup is not re-run for that).
const SHORTCUT_EXAMPLES = [
  { command: 'picode', preset: 'coding' },
  { command: 'piwork', preset: 'office,design' },
] as const;

export function renderShortcutHint(shell: SupportedShell): string[] {
  const lines = ['Tip: define shortcuts for the presets you use most, for example:'];
  for (const { command, preset } of SHORTCUT_EXAMPLES) {
    lines.push(shell === 'fish'
      ? `  abbr --add ${command} 'pi -ps ${preset}'`
      : `  alias ${command}='pi -ps ${preset}'`);
  }
  return lines;
}

export function shellIntegrationPaths(
  shell: SupportedShell,
  homeDir: string,
  configHome: string,
): string[] {
  if (shell === 'fish') {
    return [join(configHome, 'fish', 'conf.d', 'pi-presets.fish')];
  }
  return [join(configHome, 'pi-presets', 'pi.sh'), join(homeDir, `.${shell}rc`)];
}

function countOccurrences(text: string, needle: string): number {
  let count = 0;
  let index = text.indexOf(needle);
  while (index !== -1) {
    count += 1;
    index = text.indexOf(needle, index + needle.length);
  }
  return count;
}

interface ManagedBlockSpan {
  start: number;
  end: number;
}

// Refuse to guess: a block that is incomplete, repeated, or out of order could
// hold user content between a stray start marker and the next end marker, so
// both setup and teardown abort instead of rewriting it.
function locateManagedBlock(text: string, source: string): ManagedBlockSpan | undefined {
  const starts = countOccurrences(text, START_MARKER);
  const ends = countOccurrences(text, END_MARKER);
  if (starts === 0 && ends === 0) return undefined;
  if (starts !== 1 || ends !== 1) {
    throw new Error(
      `Incomplete managed block in ${source} (${starts} start marker(s), ${ends} end marker(s)); leaving it unchanged.`,
    );
  }

  const start = text.indexOf(START_MARKER);
  const end = text.indexOf(END_MARKER);
  if (end < start) {
    throw new Error(`Incomplete managed block in ${source}; leaving it unchanged.`);
  }
  return { start, end: end + END_MARKER.length };
}

function updateRc(original: string, block: string, source: string): string {
  const span = locateManagedBlock(original, source);
  if (span) {
    return original.slice(0, span.start) + block + original.slice(span.end);
  }

  const withTrailingNewline = original.length > 0 && !original.endsWith('\n')
    ? `${original}\n`
    : original;
  const separation = withTrailingNewline.length > 0 ? '\n' : '';
  return `${withTrailingNewline}${separation}${block}\n`;
}

export interface RemovalOptions {
  shells: readonly SupportedShell[];
  homeDir: string;
  configHome: string;
  dryRun?: boolean;
}

export interface RemovalResult {
  files: string[];
  rcFiles: string[];
  keptFiles: string[];
}

function hasManagedBlock(text: string): boolean {
  return text.includes(START_MARKER) || text.includes(END_MARKER);
}

function stripManagedBlock(original: string, source: string): string {
  const span = locateManagedBlock(original, source);
  if (!span) return original;

  // The install path separates an appended block with one blank line before it
  // and one newline after it; taking both back restores the original rc bytes.
  let prefix = original.slice(0, span.start);
  let suffix = original.slice(span.end);
  if (prefix.endsWith('\n\n')) prefix = prefix.slice(0, -1);
  if (suffix.startsWith('\n')) suffix = suffix.slice(1);
  return prefix + suffix;
}

export function removeShellIntegration({
  shells,
  homeDir,
  configHome,
  dryRun = false,
}: RemovalOptions): RemovalResult {
  const rcFiles: string[] = [];
  const keptFiles: string[] = [];
  const deletions: string[] = [];
  const writes: { path: string; content: string }[] = [];
  const stripped = new Map<SupportedShell, string>();
  const posixShells = shells.filter((shell) => shell !== 'fish');

  // Validate and compute every rc change first, so an incomplete managed block
  // anywhere aborts the whole removal before a single file is touched.
  for (const shell of posixShells) {
    const rcPath = shellIntegrationPaths(shell, homeDir, configHome)[1];
    if (!existsSync(rcPath)) continue;
    const original = readFileSync(rcPath, 'utf8');
    if (!hasManagedBlock(original)) continue;
    const content = stripManagedBlock(original, rcPath);
    stripped.set(shell, content);
    writes.push({ path: rcPath, content });
    rcFiles.push(rcPath);
  }

  if (shells.includes('fish')) {
    const [integrationPath] = shellIntegrationPaths('fish', homeDir, configHome);
    if (existsSync(integrationPath)) deletions.push(integrationPath);
  }

  const functionPath = join(configHome, 'pi-presets', 'pi.sh');
  const stillReferenced = (['bash', 'zsh'] as const).some((shell) => {
    const rcPath = shellIntegrationPaths(shell, homeDir, configHome)[1];
    if (!existsSync(rcPath)) return false;
    const content = stripped.get(shell) ?? readFileSync(rcPath, 'utf8');
    return hasManagedBlock(content);
  });

  if (posixShells.length > 0 && existsSync(functionPath)) {
    if (stillReferenced) {
      keptFiles.push(functionPath);
    } else {
      deletions.push(functionPath);
    }
  }

  if (!dryRun) {
    for (const write of writes) writeFileSync(write.path, write.content);
    for (const path of deletions) rmSync(path, { force: true });
    if (deletions.includes(functionPath)) {
      try {
        rmdirSync(join(configHome, 'pi-presets'));
      } catch {
        // Leave the directory alone when it still holds something else.
      }
    }
  }

  return { files: deletions, rcFiles, keptFiles };
}

export function installShellIntegration({
  shell,
  repoRoot,
  homeDir,
  configHome,
}: ShellIntegrationOptions): ShellIntegrationResult {
  if (!isSupportedShell(shell)) {
    throw new Error(`Unsupported shell: ${shell}`);
  }

  const source = renderFunctionSource(shell, repoRoot);
  if (shell === 'fish') {
    const [integrationPath] = shellIntegrationPaths(shell, homeDir, configHome);
    mkdirSync(join(configHome, 'fish', 'conf.d'), { recursive: true });
    writeFileSync(integrationPath, source);
    return { files: [integrationPath] };
  }

  const [functionPath, rcPath] = shellIntegrationPaths(shell, homeDir, configHome);
  const quotedPath = quotePosix(functionPath);
  const block = `${START_MARKER}\n[ -f ${quotedPath} ] && . ${quotedPath}\n${END_MARKER}`;
  const original = existsSync(rcPath) ? readFileSync(rcPath, 'utf8') : '';
  const updated = updateRc(original, block, rcPath);

  mkdirSync(join(configHome, 'pi-presets'), { recursive: true });
  writeFileSync(functionPath, source);
  writeFileSync(rcPath, updated);
  return { files: [functionPath, rcPath] };
}
